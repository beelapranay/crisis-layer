"""Generates the Swift side of the crisis layer's rules from the Python source of truth, plus a parity fixture.

- RulesData.swift: every regex from rules.py and pipeline.py (CRISIS, CHECKIN, OUTPUT_BLOCK, the resource and
  sentence patterns, HIGH_PRECISION), the allowed crisis numbers and the thresholds, as Swift raw strings, so the
  app never carries a hand-copied pattern.
- rules_fixture.json: what Python returns for check_input, high_precision, strip_resources and check_output on our
  own test prompts (tests.py) and on LFM3 replies from the supporter evals, plus the classifier tokenizer's ids for
  each prompt and the PyTorch model's probabilities; CrisisKit's tests must reproduce them.

    python3 export_swift.py ../app/CrisisKit
"""
import glob
import json
import os
import random
import sys

import rules
from pipeline import HIGH_PRECISION, T_CRISIS, T_RISK, high_precision
from tests import sets

HERE = os.path.dirname(os.path.abspath(__file__))
EVAL = os.path.join(os.path.dirname(HERE), "neuron-explorer", "stats", "lfm3-1.7b-persona", "eval")


def raw(s):
    """A Swift raw string literal that holds s unchanged."""
    n = 1
    while '"' + "#" * n in s:
        n += 1
    return "#" * n + '"' + s + '"' + "#" * n


def rule_list(name, compiled):
    rows = ",\n".join(f"        ({json.dumps(n)}, {raw(rx.pattern)})" for n, rx in compiled)
    return f"    static let {name}: [(String, String)] = [\n{rows},\n    ]\n"


def swift():
    out = ["// Generated by crisis_layer/export_swift.py from rules.py and pipeline.py. Do not edit by hand.\n",
           "enum RulesData {\n",
           rule_list("crisis", rules.CRISIS), rule_list("checkin", rules.CHECKIN),
           rule_list("outputBlock", rules.OUTPUT_BLOCK),
           "    static let highPrecision: [String] = [\n"
           + "".join(f"        {raw(rx.pattern)},\n" for rx in HIGH_PRECISION) + "    ]\n",
           f"    static let resource = {raw(rules._RESOURCE.pattern)}\n",
           f"    static let sentence = {raw(rules._SENTENCE.pattern)}\n",
           f"    static let phone = {raw(rules._PHONE.pattern)}\n",
           f"    static let letter = {raw(rules._LETTER.pattern)}\n",
           "    static let allowedNumbers: Set<String> = [" + ", ".join(json.dumps(n) for n in sorted(rules.ALLOWED_NUMBERS))
           + "]\n",
           f"    static let tRisk = {T_RISK}\n    static let tCrisis = {T_CRISIS}\n",
           "}\n"]
    return "".join(out)


def fixture():
    import torch
    from transformers import AutoModelForSequenceClassification, AutoTokenizer
    src = os.path.join(HERE, "model_roberta_v2")
    tok = AutoTokenizer.from_pretrained(src)
    model = AutoModelForSequenceClassification.from_pretrained(src).eval()
    inputs = sorted({t for s in sets().values() for t, _ in s})

    def probs(t):
        with torch.no_grad():
            x = tok(t, truncation=True, max_length=256, return_tensors="pt")
            return [round(v, 5) for v in torch.softmax(model(**x).logits[0].float(), -1).tolist()]
    replies = []
    for f in sorted(glob.glob(os.path.join(EVAL, "tune", "judge_heldout_*.jsonl")) +
                    glob.glob(os.path.join(EVAL, "tune", "judge_dev_v5.jsonl"))):
        replies += [json.loads(x) for x in open(f)]
    rng = random.Random(0)
    replies = rng.sample(replies, min(600, len(replies)))
    return {
        "inputs": [{"text": t, "level": rules.check_input(t)[0], "rules": list(rules.check_input(t)[1]),
                    "high_precision": high_precision(t),
                    "ids": tok(t, truncation=True, max_length=256)["input_ids"], "probs": probs(t)}
                   for t in inputs],
        "replies": [{"text": r["text"], "level": rules.check_input(r["prompt"])[0],
                     "stripped": rules.strip_resources(r["text"])[0],
                     "removed": rules.strip_resources(r["text"])[1],
                     "ok": rules.check_output(rules.strip_resources(r["text"])[0],
                                              rules.check_input(r["prompt"])[0])[0],
                     "reasons": rules.check_output(rules.strip_resources(r["text"])[0],
                                                   rules.check_input(r["prompt"])[0])[1]}
                    for r in replies],
    }


def main():
    pkg = sys.argv[1]
    src = os.path.join(pkg, "Sources", "CrisisKit", "RulesData.swift")
    fix = os.path.join(pkg, "Tests", "CrisisKitTests", "Resources", "rules_fixture.json")
    os.makedirs(os.path.dirname(src), exist_ok=True)
    os.makedirs(os.path.dirname(fix), exist_ok=True)
    open(src, "w").write(swift())
    f = fixture()
    json.dump(f, open(fix, "w"), indent=0, ensure_ascii=False)
    print(f"wrote {src} and {fix} ({len(f['inputs'])} inputs, {len(f['replies'])} replies)")


if __name__ == "__main__":
    main()
